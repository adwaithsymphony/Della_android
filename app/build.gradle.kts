// Signing: CI / local builds read keystore.properties (or DELLA_* env vars).
// The bundled keystore is a DEVELOPMENT key so the APK is installable; replace it
// with your own private key before publishing to Play.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    System.getenv(env) ?: keystoreProps.getProperty(key)

